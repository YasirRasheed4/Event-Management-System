-- Atomic booking creation, called by the browser through Supabase RPC.
create or replace function public.create_booking(
  p_event_id bigint,
  p_num_tickets integer default 1,
  p_ticket_type_id bigint default null
)
returns jsonb
language plpgsql
security definer set search_path = public
as $$
declare
  v_event public.events%rowtype;
  v_price numeric(10,2);
  v_total numeric(10,2);
  v_ref text;
  v_booking_id bigint;
begin
  if auth.uid() is null then
    raise exception 'Please login before booking.';
  end if;
  if p_num_tickets < 1 then
    raise exception 'At least one ticket is required.';
  end if;

  select * into v_event
  from public.events
  where event_id = p_event_id and status = 'published'
  for update;

  if not found then raise exception 'Event not found or not available.'; end if;
  if v_event.available_seats < p_num_tickets then raise exception 'Not enough seats available.'; end if;

  v_price := v_event.ticket_price;
  if p_ticket_type_id is not null then
    select price into v_price from public.ticket_types
    where ticket_type_id = p_ticket_type_id and event_id = p_event_id;
  end if;
  v_total := v_price * p_num_tickets;
  v_ref := 'EMS-' || to_char(current_date, 'YYYY') || '-' || lpad(nextval('public.booking_ref_seq')::text, 5, '0');

  insert into public.bookings (user_id, event_id, ticket_type_id, booking_ref, num_tickets, total_amount)
  values (auth.uid(), p_event_id, p_ticket_type_id, v_ref, p_num_tickets, v_total)
  returning booking_id into v_booking_id;

  update public.events set available_seats = available_seats - p_num_tickets
  where event_id = p_event_id;

  return jsonb_build_object('booking_id', v_booking_id, 'booking_ref', v_ref, 'total_amount', v_total);
end;
$$;

revoke all on function public.create_booking(bigint, integer, bigint) from public;
grant execute on function public.create_booking(bigint, integer, bigint) to authenticated;

