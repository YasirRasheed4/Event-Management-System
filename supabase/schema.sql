-- EventSphere Supabase schema
-- Run this file in Supabase Dashboard -> SQL Editor.
-- Supabase Auth owns passwords. Never create a password column here.

create table if not exists public.roles (
  role_id smallint primary key,
  role_name text not null unique check (role_name in ('admin', 'organizer', 'participant')),
  description text
);

insert into public.roles (role_id, role_name, description) values
  (1, 'admin', 'Full system access'),
  (2, 'organizer', 'Can create and manage events'),
  (3, 'participant', 'Can register and book tickets')
on conflict (role_id) do update set
  role_name = excluded.role_name,
  description = excluded.description;

create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role_id smallint not null default 3 references public.roles(role_id),
  full_name text not null,
  email text not null unique,
  phone text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.categories (
  category_id bigint generated by default as identity primary key,
  name text not null unique,
  icon text not null default 'tag',
  color_hex text not null default '#6366f1' check (color_hex ~ '^#[0-9a-fA-F]{6}$')
);

