-- RLS helper functions. They are server-owned and only return role checks.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where user_id = auth.uid() and role_id = 1 and is_active
  );
$$;

create or replace function public.is_organizer()
returns boolean
language sql
stable
security definer set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where user_id = auth.uid() and role_id in (1, 2) and is_active
  );
$$;

create or replace function public.prevent_non_admin_profile_changes()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  if not public.is_admin() and (new.role_id <> old.role_id or new.user_id <> old.user_id or new.is_active <> old.is_active) then
    raise exception 'Only an administrator can change profile role or status.';
  end if;
  return new;
end;
$$;

drop trigger if exists profiles_protect_role on public.profiles;
create trigger profiles_protect_role before update on public.profiles
for each row execute procedure public.prevent_non_admin_profile_changes();

