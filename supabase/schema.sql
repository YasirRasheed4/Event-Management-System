create table if not exists public.venues (
  venue_id bigint generated by default as identity primary key,
  name text not null,
  address text not null,
  city text not null,
  country text not null default 'Pakistan',
  capacity integer not null check (capacity > 0),
  contact_info text,
  facilities text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.events (
  event_id bigint generated by default as identity primary key,
  organizer_id uuid not null references public.profiles(user_id),
  category_id bigint not null references public.categories(category_id),
  venue_id bigint not null references public.venues(venue_id),
  title text not null,
  slug text not null unique,
  description text,
  banner_image text default 'default_event.jpg',
  event_date date not null,
  start_time time not null,
  end_time time not null,
  total_seats integer not null check (total_seats > 0),
  available_seats integer not null check (available_seats >= 0 and available_seats <= total_seats),
  ticket_price numeric(10,2) not null default 0 check (ticket_price >= 0),
  status text not null default 'draft' check (status in ('draft', 'published', 'cancelled', 'completed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (end_time > start_time)
);

create table if not exists public.ticket_types (
  ticket_type_id bigint generated by default as identity primary key,
  event_id bigint not null references public.events(event_id) on delete cascade,
  type_name text not null,
  price numeric(10,2) not null check (price >= 0),
  quantity integer not null check (quantity >= 0),
  sold integer not null default 0 check (sold >= 0),
  benefits text
);

create sequence if not exists public.booking_ref_seq;

create table if not exists public.bookings (
  booking_id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(user_id),
  event_id bigint not null references public.events(event_id),
  ticket_type_id bigint references public.ticket_types(ticket_type_id),
  booking_ref text not null unique,
  num_tickets integer not null default 1 check (num_tickets > 0),
  total_amount numeric(10,2) not null check (total_amount >= 0),
  status text not null default 'pending' check (status in ('pending', 'confirmed', 'cancelled', 'attended')),
  booked_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.payments (
  payment_id bigint generated by default as identity primary key,
  booking_id bigint not null unique references public.bookings(booking_id),
  amount numeric(10,2) not null check (amount >= 0),
  method text not null check (method in ('cash', 'card', 'bank_transfer', 'easypaisa', 'jazzcash')),
  status text not null default 'pending' check (status in ('pending', 'completed', 'failed', 'refunded')),
  transaction_ref text,
  paid_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.event_feedback (
  feedback_id bigint generated by default as identity primary key,
  event_id bigint not null references public.events(event_id),
  user_id uuid not null references public.profiles(user_id),
  rating smallint not null check (rating between 1 and 5),
  comment text,
  submitted_at timestamptz not null default now(),
  unique (event_id, user_id)
);

